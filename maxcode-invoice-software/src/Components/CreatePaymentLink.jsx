import React, { useEffect, useMemo, useRef, useState } from "react";
import Select from "react-select";
import CreatableSelect from "react-select/creatable";
import { apiGet, apiPost, apiPut } from "../utils/api";
import API_ENDPOINTS from "../utils/apiEndpoints";
import { showError, showSuccess } from "./ToastNotification";
import { getUnifiedSelectStyles } from "../utils/reactSelectStyles";
import {
  fetchSelectableClients,
  filterActiveSelectableRows,
  filterRowsBySearch,
} from "../utils/fetchAllEntities";

const DOMAIN_OPTIONS = [
  { value: "https://billing.maxcode.in", label: "https://billing.maxcode.in" },
  { value: "https://pay.maxcode.in", label: "https://pay.maxcode.in" },
  { value: "http://localhost:5173", label: "http://localhost:5173" },
];

const STATUS_OPTIONS = [
  { value: "pending", label: "Pending" },
  { value: "under_verification", label: "Under Verification" },
  { value: "success", label: "Success" },
  { value: "failed", label: "Failed" },
  { value: "expired", label: "Expired" },
];

const EMPTY_FORM = {
  clientRefId: "",
  clientName: "",
  businessName: "",
  phoneNumber: "",
  address: "",
  accountName: "",
  upiId: "",
  amount: "",
  domain: DOMAIN_OPTIONS[1].value,
  alias: "",
  linkExpiry: "",
  status: "pending",
  paymentDate: "",
  utrNumber: "",
  failedReason: "",
  note: "",
  temporaryClient: false,
};

const normalizeAlias = (value = "") =>
  String(value || "")
    .trim()
    .replace(/[^a-zA-Z0-9_-]/g, "")
    .slice(0, 80);

const toDateInputValue = (value) => {
  if (!value) return "";
  const raw = String(value || "").trim();
  const strictDateOnly = raw.match(/^(\d{4}-\d{2}-\d{2})$/);
  if (strictDateOnly) return strictDateOnly[1];

  const date = new Date(raw);
  if (Number.isNaN(date.getTime())) return "";

  const parts = new Intl.DateTimeFormat("en-GB", {
    timeZone: "Asia/Kolkata",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).formatToParts(date);

  const year = parts.find((part) => part.type === "year")?.value;
  const month = parts.find((part) => part.type === "month")?.value;
  const day = parts.find((part) => part.type === "day")?.value;
  if (!year || !month || !day) return "";

  return `${year}-${month}-${day}`;
};

const toEndOfDayIso = (dateValue) => {
  if (!dateValue) return null;
  const rawDate = String(dateValue || "").slice(0, 10);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(rawDate)) return null;

  return rawDate;
};

const toStartOfDayIso = (dateValue) => {
  if (!dateValue) return null;
  const rawDate = String(dateValue || "").slice(0, 10);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(rawDate)) return null;

  return rawDate;
};

const CreatePaymentLink = ({
  show,
  onClose,
  onSubmit,
  editingRecord = null,
}) => {
  const [formData, setFormData] = useState(EMPTY_FORM);
  const [errors, setErrors] = useState({});
  const [submitting, setSubmitting] = useState(false);

  const [clients, setClients] = useState([]);
  const [isClientLoading, setIsClientLoading] = useState(false);
  const [upiOptions, setUpiOptions] = useState([]);
  const [selectedClientOption, setSelectedClientOption] = useState(null);
  const [selectedAccountOption, setSelectedAccountOption] = useState(null);

  const clientSearchDebounceRef = useRef(null);
  const aliasCheckDebounceRef = useRef(null);
  const clientAbortControllerRef = useRef(null);
  const knownClientRowsRef = useRef([]);
  const hasAutoGeneratedAliasRef = useRef(false);
  const aliasCheckRequestRef = useRef(0);

  const [aliasStatus, setAliasStatus] = useState("unknown");
  const [isCheckingAlias, setIsCheckingAlias] = useState(false);

  const isViewMode = Boolean(editingRecord?.isViewMode);

  const getPaymentLinkSelectStyles = ({ hasError = false } = {}) => {
    const unifiedStyles = getUnifiedSelectStyles({ hasError });

    return {
      ...unifiedStyles,
      control: (base, state) => ({
        ...unifiedStyles.control(base, state),
        border: hasError
          ? "2px solid #dc3545"
          : state.isFocused
            ? "2px solid #007026"
            : "2px solid #e9ecef",
        boxShadow: "none",
      }),
    };
  };

  const generatedShareUrl = useMemo(() => {
    const alias = normalizeAlias(formData.alias);
    if (!alias) return "";
    return `${formData.domain}/${alias}`;
  }, [formData.alias, formData.domain]);

  const checkAliasAvailability = async (
    aliasCandidate = formData.alias,
    domainCandidate = formData.domain,
    options = {},
  ) => {
    const { silent = false } = options;
    const normalizedAlias = normalizeAlias(aliasCandidate);

    if (!normalizedAlias) {
      if (!silent) {
        showError("Alias is required");
      }
      setAliasStatus("unknown");
      return false;
    }

    const requestId = Date.now();
    aliasCheckRequestRef.current = requestId;
    setIsCheckingAlias(true);

    try {
      const response = await apiGet(
        API_ENDPOINTS.PAYMENT_LINKS.CHECK_ALIAS(
          normalizedAlias,
          domainCandidate || DOMAIN_OPTIONS[0].value,
          editingRecord?._id || editingRecord?.id || "",
        ),
        { cache: false, forceRefresh: true },
      );

      if (aliasCheckRequestRef.current !== requestId) {
        return false;
      }

      const available = response?.data?.available === true;

      if (available) {
        setAliasStatus("available");
        setErrors((prev) => ({ ...prev, alias: "" }));
        if (!silent) {
          showSuccess("Alias available");
        }
        return true;
      }

      setAliasStatus("taken");
      setErrors((prev) => ({ ...prev, alias: "This URL already exists" }));
      if (!silent) {
        showError("This URL already exists");
      }
      return false;
    } catch {
      if (!silent) {
        showError("Failed to verify alias availability");
      }
      setAliasStatus("unknown");
      return false;
    } finally {
      if (aliasCheckRequestRef.current === requestId) {
        setIsCheckingAlias(false);
      }
    }
  };

  const generateUniqueAlias = async () => {
    const baseName =
      String(formData.clientName || "")
        .replace(/[^a-zA-Z0-9]/g, "")
        .slice(0, 4)
        .toUpperCase() || "PAY";

    for (let attempt = 0; attempt < 10; attempt += 1) {
      const randomChunk = Math.random().toString(36).slice(2, 7).toUpperCase();
      const candidate = normalizeAlias(`${baseName}${randomChunk}`);

      const available = await checkAliasAvailability(
        candidate,
        formData.domain,
        {
          silent: true,
        },
      );

      if (available) {
        setFormData((prev) => ({ ...prev, alias: candidate }));
        setAliasStatus("available");
        return;
      }
    }

    setAliasStatus("unknown");
    showError("Could not auto-generate unique alias, please try again");
  };

  useEffect(() => {
    if (show) {
      document.body.style.overflow = "hidden";
    } else {
      document.body.style.overflow = "auto";
    }

    return () => {
      document.body.style.overflow = "auto";
    };
  }, [show]);

  useEffect(() => {
    if (!show) return;

    const loadMasterData = async () => {
      setIsClientLoading(true);
      try {
        const [clientRows, settingsRes] = await Promise.all([
          fetchSelectableClients({ limit: 60 }),
          apiGet(API_ENDPOINTS.BUSINESS_SETTINGS.GET),
        ]);

        const activeClients = filterActiveSelectableRows(clientRows);
        knownClientRowsRef.current = activeClients;
        setClients(activeClients);

        const upiRows = settingsRes?.data?.settings?.upiIds || [];
        const activeUpiRows = upiRows.filter(
          (item) =>
            item?.isDeleted !== true &&
            String(item?.status || "active").toLowerCase() === "active",
        );
        setUpiOptions(activeUpiRows);
      } catch {
        showError("Failed to load clients or UPI accounts");
      } finally {
        setIsClientLoading(false);
      }
    };

    loadMasterData();

    return () => {
      if (clientSearchDebounceRef.current) {
        clearTimeout(clientSearchDebounceRef.current);
      }
      if (aliasCheckDebounceRef.current) {
        clearTimeout(aliasCheckDebounceRef.current);
      }
      if (clientAbortControllerRef.current) {
        clientAbortControllerRef.current.abort();
      }
    };
  }, [show]);

  useEffect(() => {
    if (!show) return;

    if (editingRecord) {
      hasAutoGeneratedAliasRef.current = true;
      setFormData({
        clientRefId: editingRecord.clientRefId || "",
        clientName: editingRecord.clientName || "",
        businessName: editingRecord.businessName || "",
        phoneNumber: editingRecord.phoneNumber || "",
        address: editingRecord.address || "",
        accountName: editingRecord.accountName || "",
        upiId: editingRecord.upiId || "",
        amount:
          editingRecord.amount !== undefined && editingRecord.amount !== null
            ? String(editingRecord.amount)
            : "",
        domain: editingRecord.domain || DOMAIN_OPTIONS[0].value,
        alias: editingRecord.alias || "",
        linkExpiry: toDateInputValue(editingRecord.linkExpiry),
        status: String(editingRecord.status || "pending").toLowerCase(),
        paymentDate: toDateInputValue(editingRecord.paymentDate),
        utrNumber: editingRecord.utrNumber || "",
        failedReason: editingRecord.failedReason || "",
        note: editingRecord.note || "",
        temporaryClient: editingRecord.temporaryClient === true,
      });
      setAliasStatus("unknown");
      setErrors({});
      return;
    }

    hasAutoGeneratedAliasRef.current = false;
    setFormData(EMPTY_FORM);
    setAliasStatus("unknown");
    setErrors({});
  }, [editingRecord, show]);

  useEffect(() => {
    if (!show || editingRecord || isViewMode) return;
    if (formData.alias || hasAutoGeneratedAliasRef.current) return;

    hasAutoGeneratedAliasRef.current = true;
    generateUniqueAlias();
  }, [
    show,
    editingRecord,
    isViewMode,
    formData.alias,
    formData.clientName,
    formData.domain,
  ]);

  useEffect(() => {
    if (!show || !formData.alias) return;
    setAliasStatus("unknown");
  }, [show, formData.alias, formData.domain]);

  useEffect(() => {
    if (!show || isViewMode) return;

    const normalizedAlias = normalizeAlias(formData.alias);
    if (!normalizedAlias) {
      setAliasStatus("unknown");
      setIsCheckingAlias(false);
      if (aliasCheckDebounceRef.current) {
        clearTimeout(aliasCheckDebounceRef.current);
      }
      return;
    }

    if (aliasCheckDebounceRef.current) {
      clearTimeout(aliasCheckDebounceRef.current);
    }

    aliasCheckDebounceRef.current = setTimeout(() => {
      checkAliasAvailability(normalizedAlias, formData.domain, {
        silent: true,
      });
    }, 3000);

    return () => {
      if (aliasCheckDebounceRef.current) {
        clearTimeout(aliasCheckDebounceRef.current);
      }
    };
  }, [show, isViewMode, formData.alias, formData.domain]);

  useEffect(() => {
    if (!formData.clientName) {
      setSelectedClientOption(null);
      return;
    }

    if (formData.temporaryClient || !formData.clientRefId) {
      setSelectedClientOption({
        value: `temp-${formData.clientName}`,
        label: `${formData.clientName} (New)`,
        isTemporary: true,
        raw: {
          clientName: formData.clientName,
          businessName: formData.businessName,
          phoneNumber: formData.phoneNumber,
          address: formData.address,
        },
      });
      return;
    }

    const match = clients.find((client) => {
      const clientKey = String(
        client?._id || client?.id || client?.clientId || "",
      );
      return clientKey === String(formData.clientRefId || "");
    });

    if (match) {
      setSelectedClientOption({
        value: match._id || match.id || match.clientId,
        label: `${match.clientName || "Unknown"} (${match.phoneNumber || "No Phone"})`,
        raw: match,
      });
      return;
    }

    setSelectedClientOption(null);
  }, [
    clients,
    formData.clientRefId,
    formData.clientName,
    formData.businessName,
    formData.phoneNumber,
    formData.address,
  ]);

  useEffect(() => {
    if (!formData.upiId) {
      setSelectedAccountOption(null);
      return;
    }

    const match = upiOptions.find(
      (item) =>
        String(item?.upiId || "").toLowerCase() ===
        String(formData.upiId || "").toLowerCase(),
    );

    if (match) {
      setSelectedAccountOption({
        value: match.id || match.upiId,
        label: `${match.accountName || "Account"} - ${match.upiId || "N/A"}`,
        raw: match,
      });
      return;
    }

    setSelectedAccountOption({
      value: formData.upiId,
      label: `${formData.accountName || "Account"} - ${formData.upiId}`,
      raw: {
        accountName: formData.accountName,
        upiId: formData.upiId,
      },
    });
  }, [upiOptions, formData.accountName, formData.upiId]);

  const clientSelectOptions = useMemo(
    () =>
      clients.map((client) => ({
        value: client._id || client.id || client.clientId,
        label: `${client.clientName || "Unknown"} (${client.phoneNumber || "No Phone"})`,
        raw: client,
      })),
    [clients],
  );

  const accountSelectOptions = useMemo(
    () =>
      upiOptions.map((item) => ({
        value: item.id || item.upiId,
        label: `${item.accountName || "Account"} - ${item.upiId || "N/A"}`,
        raw: item,
      })),
    [upiOptions],
  );

  const handleClientSearchInput = (inputValue, meta) => {
    if (meta?.action !== "input-change") return inputValue;

    const searchText = String(inputValue || "").trim();

    if (clientSearchDebounceRef.current) {
      clearTimeout(clientSearchDebounceRef.current);
    }

    if (!searchText) {
      setClients(knownClientRowsRef.current.slice(0, 60));
      return inputValue;
    }

    const localMatches = filterRowsBySearch(
      knownClientRowsRef.current,
      searchText,
      ["clientName", "businessName", "phoneNumber", "email", "clientId"],
    );

    if (localMatches.length > 0) {
      setClients(localMatches);
      return inputValue;
    }

    clientSearchDebounceRef.current = setTimeout(async () => {
      if (clientAbortControllerRef.current) {
        clientAbortControllerRef.current.abort();
      }

      const controller = new AbortController();
      clientAbortControllerRef.current = controller;

      try {
        const rows = await fetchSelectableClients({
          search: searchText,
          limit: 60,
          signal: controller.signal,
        });

        if (controller.signal.aborted) return;

        const activeRows = filterActiveSelectableRows(rows);
        knownClientRowsRef.current = filterActiveSelectableRows([
          ...knownClientRowsRef.current,
          ...activeRows,
        ]);
        setClients(activeRows);
      } catch (error) {
        if (error?.name !== "CanceledError" && error?.code !== "ERR_CANCELED") {
          console.error(error);
        }
      }
    }, 320);

    return inputValue;
  };

  const handleCreateTemporaryClient = (inputValue) => {
    const name = String(inputValue || "").trim();
    if (!name) return;

    const tempClient = {
      value: `temp-${Date.now()}`,
      label: `${name} (New)`,
      isTemporary: true,
      raw: {
        clientName: name,
        businessName: "",
        phoneNumber: "",
        address: "",
      },
    };

    setSelectedClientOption(tempClient);
    setFormData((prev) => ({
      ...prev,
      clientRefId: "",
      clientName: name,
      businessName: "",
      phoneNumber: "",
      address: "",
      temporaryClient: true,
    }));
  };

  const handleClientSelect = (option) => {
    if (!option) {
      setSelectedClientOption(null);
      setFormData((prev) => ({
        ...prev,
        clientRefId: "",
        clientName: "",
        businessName: "",
        phoneNumber: "",
        address: "",
        temporaryClient: false,
      }));
      return;
    }

    const row = option.raw || {};
    setSelectedClientOption(option);
    setFormData((prev) => ({
      ...prev,
      clientRefId: row._id || row.id || row.clientId || "",
      clientName: row.clientName || "",
      businessName: row.businessName || "",
      phoneNumber: row.phoneNumber || "",
      address: row.address || "",
      temporaryClient: option.isTemporary === true,
    }));

    if (errors.clientName) {
      setErrors((prev) => ({ ...prev, clientName: "" }));
    }
  };

  const handleAccountSelect = (option) => {
    if (!option) {
      setSelectedAccountOption(null);
      setFormData((prev) => ({
        ...prev,
        accountName: "",
        upiId: "",
      }));
      return;
    }

    const row = option.raw || {};
    setSelectedAccountOption(option);
    setFormData((prev) => ({
      ...prev,
      accountName: row.accountName || "",
      upiId: String(row.upiId || "").toLowerCase(),
    }));

    if (errors.accountName || errors.upiId) {
      setErrors((prev) => ({
        ...prev,
        accountName: "",
        upiId: "",
      }));
    }
  };

  const handleInputChange = (event) => {
    const { name, value } = event.target;

    let nextValue = value;
    if (name === "alias") {
      nextValue = normalizeAlias(value);
    }
    if (name === "upiId") {
      nextValue = String(value || "")
        .trim()
        .toLowerCase();
    }
    if (name === "phoneNumber") {
      nextValue = String(value || "")
        .replace(/\D/g, "")
        .slice(0, 10);
    }
    if (name === "amount") {
      nextValue = String(value || "")
        .replace(/[^0-9.]/g, "")
        .replace(/(\..*)\./g, "$1");
    }

    setFormData((prev) => ({
      ...prev,
      [name]: nextValue,
    }));

    if (errors[name]) {
      setErrors((prev) => ({
        ...prev,
        [name]: "",
      }));
    }
  };

  const validateForm = () => {
    const nextErrors = {};

    if (!String(formData.clientName || "").trim()) {
      nextErrors.clientName = "Client name is required";
    }

    if (!String(formData.accountName || "").trim()) {
      nextErrors.accountName = "Account name is required";
    }

    if (!String(formData.upiId || "").trim()) {
      nextErrors.upiId = "UPI ID is required";
    }

    const amountValue = Number(formData.amount);
    if (!Number.isFinite(amountValue) || amountValue <= 0) {
      nextErrors.amount = "Amount should be greater than zero";
    }

    if (!String(formData.domain || "").trim()) {
      nextErrors.domain = "Domain is required";
    }

    if (!normalizeAlias(formData.alias)) {
      nextErrors.alias = "Alias is required";
    }

    if (
      String(formData.status || "").toLowerCase() === "success" &&
      !String(formData.paymentDate || "").trim()
    ) {
      nextErrors.paymentDate = "Payment date is required for success status";
    }

    if (
      String(formData.status || "").toLowerCase() === "failed" &&
      !String(formData.failedReason || "").trim()
    ) {
      nextErrors.failedReason = "Failed reason is required for failed status";
    }

    setErrors(nextErrors);

    if (Object.keys(nextErrors).length > 0) {
      showError(Object.values(nextErrors)[0]);
      return false;
    }

    return true;
  };

  const handleSubmit = async (event) => {
    event.preventDefault();
    event.stopPropagation();

    if (isViewMode) return;

    if (!validateForm()) return;

    const isAliasAvailable = await checkAliasAvailability(
      formData.alias,
      formData.domain,
      { silent: true },
    );

    if (!isAliasAvailable) {
      showError("This URL already exists");
      return;
    }

    setSubmitting(true);

    const payload = {
      ...formData,
      alias: normalizeAlias(formData.alias),
      upiId: String(formData.upiId || "")
        .trim()
        .toLowerCase(),
      amount: Number(formData.amount || 0),
      linkExpiry: toEndOfDayIso(formData.linkExpiry),
      paymentDate: ["success", "under_verification"].includes(
        String(formData.status || "").toLowerCase(),
      )
        ? toStartOfDayIso(formData.paymentDate)
        : null,
      failedReason:
        String(formData.status || "").toLowerCase() === "failed"
          ? String(formData.failedReason || "").trim()
          : "",
      temporaryClient: formData.temporaryClient === true,
    };

    try {
      if (editingRecord && !isViewMode) {
        const targetId = String(
          editingRecord._id || editingRecord.id || "",
        ).trim();
        if (!targetId) {
          showError("Unable to update payment link: missing record id");
          setSubmitting(false);
          return;
        }
        await apiPut(
          API_ENDPOINTS.PAYMENT_LINKS.UPDATE(encodeURIComponent(targetId)),
          {
            ...payload,
            recordId: targetId,
          },
        );
        showSuccess("Payment link updated successfully");
      } else {
        await apiPost(API_ENDPOINTS.PAYMENT_LINKS.CREATE, payload);
        showSuccess("Payment link created successfully");
      }

      if (onSubmit) {
        onSubmit(payload);
      }
    } catch (error) {
      const apiError =
        error?.response?.data?.error || "Failed to save payment link";
      if (String(apiError).toLowerCase().includes("already exists")) {
        setAliasStatus("taken");
        setErrors((prev) => ({ ...prev, alias: "This URL already exists" }));
      }
      showError(apiError);
    } finally {
      setSubmitting(false);
    }
  };

  if (!show) return null;

  const modalTitle = editingRecord
    ? isViewMode
      ? `View Payment Link - ${editingRecord.alias || editingRecord.clientName || ""}`
      : `Edit Payment Link - ${editingRecord.alias || editingRecord.clientName || ""}`
    : "Add New Payment Link";

  return (
    <div
      className={`modal ${show ? "show d-block" : "d-none"}`}
      tabIndex="-1"
      role="dialog"
      style={{ backgroundColor: "rgba(0,0,0,0.5)" }}
    >
      <div className="modal-dialog modal-xl" role="document">
        <div className="modal-content">
          <div className="modal-header">
            <h5 className="modal-title">{modalTitle}</h5>
            <button
              type="button"
              className="btn-close"
              onClick={onClose}
            ></button>
          </div>

          <div className="modal-body">
            <form id="paymentLinkForm" onSubmit={handleSubmit} noValidate>
              <div className="row">
                <div className="col-md-4 mb-3">
                  <label className="form-label">
                    <i className="fas fa-user me-2 text-primary"></i>
                    Select Client <span className="text-danger">*</span>
                  </label>
                  <CreatableSelect
                    classNamePrefix="react-select"
                    isClearable
                    isDisabled={isViewMode}
                    isLoading={isClientLoading}
                    allowCreateWhileLoading={true}
                    createOptionPosition="first"
                    noOptionsMessage={() =>
                      "Type client name and press Enter to add new client"
                    }
                    isValidNewOption={(inputValue, _, options) => {
                      const normalized = String(inputValue || "")
                        .trim()
                        .toLowerCase();
                      if (!normalized) return false;
                      return true;
                    }}
                    placeholder="Search client or add new client"
                    options={clientSelectOptions}
                    value={selectedClientOption}
                    onInputChange={handleClientSearchInput}
                    onChange={handleClientSelect}
                    onCreateOption={handleCreateTemporaryClient}
                    formatCreateLabel={(inputValue) =>
                      `Add \"${String(inputValue || "").trim()}\" as new client`
                    }
                    styles={getPaymentLinkSelectStyles({
                      hasError: Boolean(errors.clientName),
                    })}
                  />
                  {errors.clientName && (
                    <div className="invalid-feedback d-block">
                      {errors.clientName}
                    </div>
                  )}
                </div>

                <div className="col-md-4 mb-3">
                  <label className="form-label">
                    <i className="fas fa-user-tag me-2 text-primary"></i>
                    Client Name <span className="text-danger">*</span>
                  </label>
                  <input
                    type="text"
                    name="clientName"
                    className={`form-control modern-input ${errors.clientName ? "is-invalid" : ""}`}
                    value={formData.clientName}
                    onChange={handleInputChange}
                    readOnly={isViewMode}
                    placeholder="Enter Client Name"
                  />
                </div>

                <div className="col-md-4 mb-3">
                  <label className="form-label">
                    <i className="fas fa-building me-2 text-primary"></i>
                    Business Name
                  </label>
                  <input
                    type="text"
                    name="businessName"
                    className="form-control modern-input"
                    value={formData.businessName}
                    onChange={handleInputChange}
                    readOnly={isViewMode}
                    placeholder="Enter Business Name"
                  />
                </div>

                <div className="col-md-4 mb-3">
                  <label className="form-label">
                    <i className="fas fa-phone me-2 text-primary"></i>
                    Phone Number
                  </label>
                  <div className="input-group">
                    <span className="input-group-text flag-india">
                      <img
                        src="https://flagcdn.com/w40/in.png"
                        alt="India"
                        className="flag-icon"
                      />
                      +91
                    </span>
                    <input
                      type="tel"
                      name="phoneNumber"
                      className="form-control modern-input rounded-end-3"
                      value={formData.phoneNumber}
                      onChange={handleInputChange}
                      readOnly={isViewMode}
                      minLength="10"
                      maxLength="10"
                      placeholder="10-digit mobile number"
                    />
                  </div>
                </div>

                <div className="col-md-4 mb-3">
                  <label className="form-label">
                    <i className="fas fa-map-marker-alt me-2 text-primary"></i>
                    Address
                  </label>
                  <input
                    type="text"
                    name="address"
                    className="form-control modern-input"
                    value={formData.address}
                    onChange={handleInputChange}
                    readOnly={isViewMode}
                    placeholder="Enter Address"
                  />
                </div>

                <div className="col-md-4 mb-3">
                  <label className="form-label">
                    <i className="fas fa-wallet me-2 text-primary"></i>
                    Select Account <span className="text-danger">*</span>
                  </label>
                  <Select
                    classNamePrefix="react-select"
                    isClearable
                    isDisabled={isViewMode}
                    placeholder="Select UPI account"
                    options={accountSelectOptions}
                    value={selectedAccountOption}
                    onChange={handleAccountSelect}
                    styles={getPaymentLinkSelectStyles({
                      hasError: Boolean(errors.accountName || errors.upiId),
                    })}
                  />
                  {(errors.accountName || errors.upiId) && (
                    <div className="invalid-feedback d-block">
                      {errors.accountName || errors.upiId}
                    </div>
                  )}
                </div>

                <div className="col-md-4 mb-3">
                  <label className="form-label">
                    <i className="fas fa-id-card me-2 text-primary"></i>
                    Account Name <span className="text-danger">*</span>
                  </label>
                  <input
                    type="text"
                    name="accountName"
                    className={`form-control modern-input ${errors.accountName ? "is-invalid" : ""}`}
                    value={formData.accountName}
                    onChange={handleInputChange}
                    readOnly={isViewMode}
                    placeholder="Account Name"
                  />
                </div>

                <div className="col-md-4 mb-3">
                  <label className="form-label">
                    <i className="fas fa-at me-2 text-primary"></i>
                    UPI ID <span className="text-danger">*</span>
                  </label>
                  <input
                    type="text"
                    name="upiId"
                    className={`form-control modern-input ${errors.upiId ? "is-invalid" : ""}`}
                    value={formData.upiId}
                    onChange={handleInputChange}
                    readOnly={isViewMode}
                    placeholder="example@upi"
                  />
                </div>

                <div className="col-md-4 mb-3">
                  <label className="form-label">
                    <i className="fas fa-rupee-sign me-2 text-primary"></i>
                    Amount <span className="text-danger">*</span>
                  </label>
                  <input
                    type="text"
                    name="amount"
                    inputMode="decimal"
                    pattern="[0-9]*[.]?[0-9]*"
                    className={`form-control modern-input ${errors.amount ? "is-invalid" : ""}`}
                    value={formData.amount}
                    onChange={handleInputChange}
                    readOnly={isViewMode}
                    placeholder="0.00"
                  />
                  {errors.amount && (
                    <div className="invalid-feedback d-block">
                      {errors.amount}
                    </div>
                  )}
                </div>

                <div className="col-md-4 mb-3">
                  <label className="form-label">
                    <i className="fas fa-globe me-2 text-primary"></i>
                    Select Domain <span className="text-danger">*</span>
                  </label>
                  <Select
                    classNamePrefix="react-select"
                    isDisabled={isViewMode}
                    options={DOMAIN_OPTIONS}
                    value={
                      DOMAIN_OPTIONS.find(
                        (item) => item.value === formData.domain,
                      ) || null
                    }
                    onChange={(option) =>
                      setFormData((prev) => ({
                        ...prev,
                        domain: option?.value || DOMAIN_OPTIONS[0].value,
                      }))
                    }
                    styles={getPaymentLinkSelectStyles({
                      hasError: Boolean(errors.domain),
                    })}
                  />
                  {errors.domain && (
                    <div className="invalid-feedback d-block">
                      {errors.domain}
                    </div>
                  )}
                </div>

                <div className="col-md-4 mb-3">
                  <label className="form-label d-flex justify-content-between align-items-center">
                    <span>
                      <i className="fas fa-link me-2 text-primary"></i>
                      Alias <span className="text-danger">*</span>
                    </span>
                    {!isViewMode && String(formData.alias || "").trim() && (
                      <span
                        className={`small fw-semibold ${
                          isCheckingAlias
                            ? "text-muted"
                            : aliasStatus === "available"
                              ? "text-success"
                              : aliasStatus === "taken"
                                ? "text-danger"
                                : "text-muted"
                        }`}
                      >
                        {isCheckingAlias && (
                          <>
                            <i className="fas fa-spinner fa-spin me-1"></i>
                            Checking
                          </>
                        )}
                        {!isCheckingAlias && aliasStatus === "available" && (
                          <>
                            <i className="fas fa-check-circle me-1"></i>
                            Alias available
                          </>
                        )}
                        {!isCheckingAlias && aliasStatus === "taken" && (
                          <>
                            <i className="fas fa-times-circle me-1"></i>
                            Alias not available
                          </>
                        )}
                      </span>
                    )}
                  </label>
                  <div className="input-group">
                    <input
                      type="text"
                      name="alias"
                      className={`form-control modern-input ${errors.alias ? "is-invalid" : ""}`}
                      value={formData.alias}
                      onChange={handleInputChange}
                      readOnly={isViewMode}
                      placeholder="A4F5T"
                    />
                    {!isViewMode && (
                      <button
                        type="button"
                        className="btn btn-outline-secondary"
                        onClick={() => generateUniqueAlias()}
                      >
                        Auto
                      </button>
                    )}
                  </div>
                  {errors.alias && aliasStatus !== "taken" && (
                    <div className="invalid-feedback d-block">
                      {errors.alias}
                    </div>
                  )}
                </div>

                <div className="col-md-4 mb-3">
                  <label className="form-label">
                    <i className="fas fa-calendar-alt me-2 text-primary"></i>
                    Link Expiry
                  </label>
                  <input
                    type="date"
                    name="linkExpiry"
                    className="form-control modern-input"
                    value={formData.linkExpiry}
                    onChange={handleInputChange}
                    readOnly={isViewMode}
                  />
                </div>

                <div className="col-md-4 mb-3">
                  <label className="form-label">
                    <i className="fas fa-globe me-2 text-primary"></i>
                    Generated URL
                  </label>
                  <input
                    type="text"
                    className="form-control modern-input"
                    value={generatedShareUrl}
                    readOnly
                    placeholder="URL will appear here"
                  />
                </div>

                <div className="col-md-4 mb-3">
                  <label className="form-label">
                    <i className="fas fa-sticky-note me-2 text-primary"></i>
                    Note
                  </label>
                  <input
                    type="text"
                    name="note"
                    className="form-control modern-input"
                    value={formData.note}
                    onChange={handleInputChange}
                    readOnly={isViewMode}
                    placeholder="Enter Note"
                  />
                </div>

                <div className="col-md-4 mb-3">
                  <label className="form-label">
                    <i className="fas fa-info-circle me-2 text-primary"></i>
                    Status
                  </label>
                  <Select
                    classNamePrefix="react-select"
                    isDisabled={isViewMode}
                    options={STATUS_OPTIONS}
                    value={
                      STATUS_OPTIONS.find(
                        (item) => item.value === formData.status,
                      ) || STATUS_OPTIONS[0]
                    }
                    onChange={(option) =>
                      setFormData((prev) => ({
                        ...prev,
                        status: option?.value || "pending",
                      }))
                    }
                    styles={getPaymentLinkSelectStyles()}
                  />
                </div>

                {(formData.status === "success" ||
                  formData.status === "under_verification") && (
                  <div className="col-md-4 mb-3">
                    <label className="form-label">
                      <i className="fas fa-calendar-check me-2 text-success"></i>
                      Payment Date
                      {formData.status === "success" && (
                        <span className="text-danger"> *</span>
                      )}
                    </label>
                    <input
                      type="date"
                      className={`form-control modern-input ${errors.paymentDate ? "is-invalid" : ""}`}
                      name="paymentDate"
                      value={formData.paymentDate || ""}
                      onChange={handleInputChange}
                      readOnly={isViewMode}
                    />
                    {errors.paymentDate && (
                      <div className="invalid-feedback d-block">
                        {errors.paymentDate}
                      </div>
                    )}
                  </div>
                )}

                {(formData.status === "success" ||
                  formData.status === "under_verification") && (
                  <div className="col-md-4 mb-3">
                    <label className="form-label">
                      <i className="fas fa-hashtag me-2 text-success"></i>
                      Transaction ID / UTR Number
                    </label>
                    <input
                      type="text"
                      className="form-control modern-input"
                      name="utrNumber"
                      value={formData.utrNumber || ""}
                      placeholder="e.g. 426211109876543"
                      onChange={handleInputChange}
                      readOnly={isViewMode}
                      maxLength={50}
                    />
                  </div>
                )}

                {formData.status === "failed" && (
                  <div className="col-md-8 mb-3">
                    <label className="form-label">
                      <i className="fas fa-exclamation-triangle me-2 text-danger"></i>
                      Failed Reason <span className="text-danger">*</span>
                    </label>
                    <input
                      type="text"
                      className={`form-control modern-input ${errors.failedReason ? "is-invalid" : ""}`}
                      name="failedReason"
                      value={formData.failedReason || ""}
                      placeholder="Enter failure reason"
                      onChange={handleInputChange}
                      readOnly={isViewMode}
                    />
                    {errors.failedReason && (
                      <div className="invalid-feedback d-block">
                        {errors.failedReason}
                      </div>
                    )}
                  </div>
                )}
              </div>
            </form>
          </div>

          <div className="modal-footer">
            <button
              type="button"
              className="btn btn-secondary"
              onClick={onClose}
            >
              <i className="fas fa-times me-2"></i>
              {isViewMode ? "Close" : "Cancel"}
            </button>
            {!isViewMode && (
              <button
                type="submit"
                form="paymentLinkForm"
                className="btn btn-success"
                disabled={submitting}
              >
                {submitting ? (
                  <>
                    <span
                      className="spinner-border spinner-border-sm me-2"
                      role="status"
                      aria-hidden="true"
                    ></span>
                    Saving...
                  </>
                ) : (
                  <>
                    <i className="fas fa-check me-2"></i>
                    {editingRecord
                      ? "Update Payment Link"
                      : "Save Payment Link"}
                  </>
                )}
              </button>
            )}
          </div>
        </div>
      </div>

      <style>{`
        .flag-india {
          background: linear-gradient(135deg, #ff9933, #ffffff, #138808);
          border: 2px solid #e9ecef;
          border-right: none;
          border-radius: 10px 0 0 10px;
          font-weight: 600;
          color: #333;
        }

        .flag-icon {
          width: 20px;
          height: 15px;
          margin-right: 8px;
          border-radius: 2px;
        }

        .input-group > .form-control {
          border-radius: 0;
        }

        .input-group > .form-control:focus {
          z-index: 0;
          box-shadow: none;
        }
      `}</style>
    </div>
  );
};

export default CreatePaymentLink;
